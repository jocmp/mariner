//! Importing and exporting subscription lists.

use common::{Network, local_account};
use futures_executor::block_on;
use mariner_core::{ArticleFilter, ArticleScope, OpmlImport};

mod common;

fn rss(title: &str, guid: &str) -> String {
    format!(
        r#"<rss version="2.0"><channel><title>{title}</title><link>https://example.com/</link><item><guid>{guid}</guid></item></channel></rss>"#
    )
}

const LIST: &str = r#"<?xml version="1.0"?>
<opml version="2.0"><body>
  <outline text="Loose" xmlUrl="https://example.com/loose.xml"/>
  <outline text="News">
    <outline text="Daily" xmlUrl="https://example.com/daily.xml" htmlUrl="https://daily.example.com/"/>
    <outline text="Existing" xmlUrl="https://example.com/existing.xml"/>
  </outline>
</body></opml>"#;

#[test]
fn imports_without_fetching_then_refreshes() {
    block_on(async {
        let network = Network::default()
            .with("https://example.com/loose.xml", &rss("Loose Feed", "l1"))
            .with("https://example.com/daily.xml", &rss("Daily Feed", "d1"))
            .with("https://example.com/existing.xml", &rss("Existing", "e1"));
        let (_dir, account) = local_account(&network).await;
        account
            .subscribe("https://example.com/existing.xml", None)
            .await
            .unwrap();
        network.clear_requests();

        let imported = account.import_opml(LIST.as_bytes()).await.unwrap();
        assert_eq!(
            imported,
            OpmlImport {
                added: 2,
                existing: 1
            }
        );
        assert!(
            network.requested_urls().is_empty(),
            "importing fetches nothing"
        );

        let feeds = account.feeds().await.unwrap();
        let listed: Vec<(&str, &[String])> = feeds
            .iter()
            .map(|feed| (feed.title.as_str(), feed.tag_names.as_slice()))
            .collect();
        assert_eq!(
            listed,
            [
                ("Daily", &["News".to_string()][..]),
                ("Existing", &["News".to_string()][..]),
                ("Loose", &[][..]),
            ]
        );
        let daily = feeds.iter().find(|feed| feed.title == "Daily").unwrap();
        assert_eq!(
            daily.site_url.as_deref(),
            Some("https://daily.example.com/")
        );

        account.refresh(None).await.unwrap();
        let articles = account
            .articles(ArticleFilter::All, &ArticleScope::Tag("News".into()), 10, 0)
            .await
            .unwrap();
        assert_eq!(
            articles.len(),
            2,
            "a refresh brings the imported feeds' articles"
        );
        let titles: Vec<String> = account
            .feeds()
            .await
            .unwrap()
            .into_iter()
            .map(|feed| feed.title)
            .collect();
        assert_eq!(titles, ["Daily Feed", "Existing", "Loose Feed"]);
    });
}

#[test]
fn exports_feeds_in_their_folders() {
    block_on(async {
        let network = Network::default()
            .with("https://example.com/a.xml", &rss("A &amp; B", "a1"))
            .with("https://example.com/c.xml", &rss("C", "c1"));
        let (_dir, account) = local_account(&network).await;
        account
            .subscribe("https://example.com/a.xml", None)
            .await
            .unwrap();
        let c = account
            .subscribe("https://example.com/c.xml", None)
            .await
            .unwrap();
        account
            .update_feed(&c, &c.title, &["Tech".to_string()])
            .await
            .unwrap();

        let exported = account.export_opml().await.unwrap();
        assert_eq!(
            exported,
            r#"<?xml version="1.0" encoding="UTF-8"?>
<!-- OPML generated by Mariner -->
<opml version="1.1">
  <head>
    <title>Mariner Export</title>
  </head>
  <body>
    <outline text="A &amp; B" title="A &amp; B" description="" type="rss" version="RSS" htmlUrl="https://example.com/" xmlUrl="https://example.com/a.xml"/>
    <outline text="Tech" title="Tech">
      <outline text="C" title="C" description="" type="rss" version="RSS" htmlUrl="https://example.com/" xmlUrl="https://example.com/c.xml"/>
    </outline>
  </body>
</opml>
"#
        );

        let (_dir, other) = local_account(&Network::default()).await;
        let imported = other.import_opml(exported.as_bytes()).await.unwrap();
        assert_eq!(imported.added, 2, "an export imports back");
    });
}

#[test]
fn rejects_a_file_that_isnt_opml() {
    block_on(async {
        let (_dir, account) = local_account(&Network::default()).await;
        let error = account
            .import_opml(b"<html><body>Not a list</body></html>")
            .await
            .expect_err("HTML isn't OPML");
        assert!(matches!(error, mariner_core::Error::Opml(_)), "{error:?}");
    });
}
