//! Checks every query in `queries/<kind>/*.sql` against the schema its
//! migrations build, and turns the queries into constants.
//!
//! For each kind of database (`account`, `app`), this applies
//! `migrations/<kind>` to an in-memory SQLite database, then prepares each
//! query. A query naming a missing table or column, or with a syntax error,
//! fails the build with its file and line. The constants are written to
//! `$OUT_DIR/sql.rs` as `sql::<kind>::<file>::<NAME>`.
//!
//! A query file is a series of statements, each under a `-- name: <name>`
//! header. Comment lines right after the header document the constant;
//! comment lines before the first header document the file's module.

use std::fmt::Write as _;
use std::fs;
use std::path::{Path, PathBuf};

use rusqlite::Connection;

const KINDS: [&str; 2] = ["account", "app"];

fn main() {
    println!("cargo::rerun-if-changed=migrations");
    println!("cargo::rerun-if-changed=queries");

    let mut errors = Vec::new();
    let mut code = String::from("// Generated by build.rs from queries/. Don't edit.\n");
    for kind in KINDS {
        let connection = match migrated(kind) {
            Ok(connection) => connection,
            Err(error) => {
                errors.push(error);
                continue;
            }
        };
        let files = sql_files(&Path::new("queries").join(kind));
        if files.is_empty() {
            continue;
        }
        writeln!(code, "pub(crate) mod {kind} {{").unwrap();
        for path in files {
            match query_file(&path) {
                Ok(file) => {
                    errors.extend(check(&connection, &path, &file));
                    write_module(&mut code, &path, &file);
                }
                Err(error) => errors.push(error),
            }
        }
        code.push_str("}\n");
    }

    for error in &errors {
        println!("cargo::error={error}");
    }
    let out = PathBuf::from(std::env::var("OUT_DIR").unwrap()).join("sql.rs");
    fs::write(out, code).unwrap();
}

/// An in-memory database with every migration of `kind` applied, in
/// version order.
fn migrated(kind: &str) -> Result<Connection, String> {
    let connection = Connection::open_in_memory().map_err(|error| error.to_string())?;
    let mut migrations: Vec<(u32, PathBuf)> = sql_files(&Path::new("migrations").join(kind))
        .into_iter()
        .filter_map(|path| Some((version(&path)?, path)))
        .collect();
    migrations.sort();
    for (_, path) in migrations {
        let sql =
            fs::read_to_string(&path).map_err(|error| format!("{}: {error}", path.display()))?;
        connection
            .execute_batch(&sql)
            .map_err(|error| format!("{}: {error}", path.display()))?;
    }
    Ok(connection)
}

/// `V12__name.sql` -> 12.
fn version(path: &Path) -> Option<u32> {
    let stem = path.file_stem()?.to_str()?;
    stem.strip_prefix('V')?.split("__").next()?.parse().ok()
}

fn sql_files(dir: &Path) -> Vec<PathBuf> {
    let Ok(entries) = fs::read_dir(dir) else {
        return Vec::new();
    };
    let mut files: Vec<PathBuf> = entries
        .filter_map(|entry| Some(entry.ok()?.path()))
        .filter(|path| path.extension().is_some_and(|ext| ext == "sql"))
        .collect();
    files.sort();
    files
}

struct QueryFile {
    docs: Vec<String>,
    queries: Vec<Query>,
}

struct Query {
    name: String,
    /// The line of its `-- name:` header.
    line: usize,
    docs: Vec<String>,
    sql: String,
}

fn query_file(path: &Path) -> Result<QueryFile, String> {
    let text = fs::read_to_string(path).map_err(|error| format!("{}: {error}", path.display()))?;
    let mut file = QueryFile {
        docs: Vec::new(),
        queries: Vec::new(),
    };
    for (index, line) in text.lines().enumerate() {
        let trimmed = line.trim();
        if let Some(name) = trimmed.strip_prefix("-- name:") {
            let name = name.trim().to_string();
            let line = index + 1;
            if !name
                .chars()
                .all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '_')
                || name.is_empty()
            {
                return Err(format!(
                    "{}:{line}: `{name}` isn't a snake_case name",
                    path.display()
                ));
            }
            if file.queries.iter().any(|query| query.name == name) {
                return Err(format!(
                    "{}:{line}: `{name}` is defined twice",
                    path.display()
                ));
            }
            file.queries.push(Query {
                name,
                line,
                docs: Vec::new(),
                sql: String::new(),
            });
            continue;
        }
        let comment = trimmed.strip_prefix("--").map(str::trim);
        match file.queries.last_mut() {
            None => {
                if let Some(comment) = comment {
                    file.docs.push(comment.to_string());
                }
            }
            Some(query) if query.sql.is_empty() && comment.is_some() => {
                query.docs.push(comment.unwrap().to_string());
            }
            Some(query) => {
                if !(query.sql.is_empty() && trimmed.is_empty()) {
                    query.sql.push_str(line);
                    query.sql.push('\n');
                }
            }
        }
    }
    for query in &mut file.queries {
        query.sql = query
            .sql
            .trim()
            .trim_end_matches(';')
            .trim_end()
            .to_string();
    }
    Ok(file)
}

/// Prepares each query, so SQLite checks its syntax, tables and columns.
fn check(connection: &Connection, path: &Path, file: &QueryFile) -> Vec<String> {
    file.queries
        .iter()
        .filter_map(|query| {
            let location = format!("{}:{}: `{}`", path.display(), query.line, query.name);
            if query.sql.is_empty() {
                return Some(format!("{location}: has no SQL"));
            }
            connection
                .prepare(&query.sql)
                .err()
                .map(|error| format!("{location}: {error}"))
        })
        .collect()
}

fn write_module(code: &mut String, path: &Path, file: &QueryFile) {
    let module = path.file_stem().unwrap().to_str().unwrap();
    writeln!(code, "    pub(crate) mod {module} {{").unwrap();
    for doc in &file.docs {
        writeln!(code, "        //! {doc}").unwrap();
    }
    for query in &file.queries {
        for doc in &query.docs {
            writeln!(code, "        /// {doc}").unwrap();
        }
        writeln!(
            code,
            "        pub(crate) const {}: &str = {:?};",
            query.name.to_ascii_uppercase(),
            query.sql
        )
        .unwrap();
    }
    code.push_str("    }\n");
}
