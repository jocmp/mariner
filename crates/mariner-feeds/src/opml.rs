//! OPML: reading a subscription list, and writing one.
//!
//! Reading follows NetNewsWire's normalizing: folders are one level deep,
//! so a feed in a nested folder goes in its outermost named folder; a
//! folder without a name passes its feeds up; a feed is listed once. As
//! folders are tags here, a feed in several folders is one subscription
//! with each folder.

use quick_xml::XmlVersion;
use quick_xml::escape::resolve_xml_entity;
use quick_xml::events::{BytesStart, Event};
use quick_xml::reader::Reader;

use crate::decode::decode;

/// A feed in a subscription list.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Subscription {
    pub feed_url: String,
    pub title: Option<String>,
    pub site_url: Option<String>,
    /// The folders it's in, in the order the list names them; empty when
    /// it's in none.
    pub folders: Vec<String>,
}

#[derive(Debug, thiserror::Error)]
pub enum OpmlError {
    #[error("not an OPML file")]
    NotOpml,
    #[error("couldn't read the OPML: {0}")]
    Xml(String),
}

/// The subscriptions in an OPML document, in the order it lists them.
pub fn parse(bytes: &[u8]) -> Result<Vec<Subscription>, OpmlError> {
    let text = decode(bytes, None).text;
    let mut reader = Reader::from_str(&text);
    let mut subscriptions: Vec<Subscription> = Vec::new();
    // Each open outline: the folder name it set, if any.
    let mut open: Vec<Option<String>> = Vec::new();
    let mut is_opml = false;
    loop {
        let (outline, closes) = match reader.read_event() {
            Ok(Event::Start(start)) if is(&start, "opml") => {
                is_opml = true;
                continue;
            }
            Ok(Event::Start(start)) if is(&start, "outline") => (attributes(&start), false),
            Ok(Event::Empty(start)) if is(&start, "outline") => (attributes(&start), true),
            Ok(Event::End(end)) if end.name().as_ref().eq_ignore_ascii_case("outline") => {
                open.pop();
                continue;
            }
            Ok(Event::Eof) => break,
            Err(error) => return Err(OpmlError::Xml(error.to_string())),
            Ok(_) => continue,
        };
        let title = outline
            .get("title")
            .or(outline.get("text"))
            .map(|title| title.trim().to_string())
            .filter(|title| !title.is_empty());
        let feed_url = outline
            .get("xmlurl")
            .map(|url| url.trim().to_string())
            .filter(|url| !url.is_empty());
        match feed_url {
            Some(feed_url) => {
                let folder = open.iter().flatten().next().cloned();
                add(
                    &mut subscriptions,
                    Subscription {
                        feed_url,
                        title,
                        site_url: outline
                            .get("htmlurl")
                            .map(|url| url.trim().to_string())
                            .filter(|url| !url.is_empty()),
                        folders: folder.into_iter().collect(),
                    },
                );
                if !closes {
                    open.push(None);
                }
            }
            None if !closes => open.push(title),
            None => {}
        }
    }
    if !is_opml {
        return Err(OpmlError::NotOpml);
    }
    Ok(subscriptions)
}

/// An OPML document listing `subscriptions`: those in no folder first, then
/// each folder with its feeds, all by name. A feed in several folders is
/// listed in each.
pub fn write(subscriptions: &[Subscription]) -> String {
    let mut sorted: Vec<&Subscription> = subscriptions.iter().collect();
    sorted.sort_by_key(|subscription| sort_key(name(subscription)));
    let mut folders: Vec<&str> = sorted
        .iter()
        .flat_map(|subscription| subscription.folders.iter().map(String::as_str))
        .collect();
    folders.sort_by_key(|folder| sort_key(folder));
    folders.dedup();

    let mut opml = String::from(
        "<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n\
         <!-- OPML generated by Mariner -->\n\
         <opml version=\"1.1\">\n  <head>\n    <title>Mariner Export</title>\n  </head>\n  <body>\n",
    );
    for subscription in sorted
        .iter()
        .filter(|subscription| subscription.folders.is_empty())
    {
        write_feed(&mut opml, subscription, "    ");
    }
    for folder in folders {
        let folder_name = escape(folder);
        opml.push_str(&format!(
            "    <outline text=\"{folder_name}\" title=\"{folder_name}\">\n"
        ));
        for subscription in sorted
            .iter()
            .filter(|subscription| subscription.folders.iter().any(|name| name == folder))
        {
            write_feed(&mut opml, subscription, "      ");
        }
        opml.push_str("    </outline>\n");
    }
    opml.push_str("  </body>\n</opml>\n");
    opml
}

/// Adds a subscription, or the folder of one listed already.
fn add(subscriptions: &mut Vec<Subscription>, subscription: Subscription) {
    match subscriptions
        .iter_mut()
        .find(|listed| listed.feed_url == subscription.feed_url)
    {
        Some(listed) => {
            for folder in subscription.folders {
                if !listed.folders.contains(&folder) {
                    listed.folders.push(folder);
                }
            }
            if listed.title.is_none() {
                listed.title = subscription.title;
            }
            if listed.site_url.is_none() {
                listed.site_url = subscription.site_url;
            }
        }
        None => subscriptions.push(subscription),
    }
}

fn is(start: &BytesStart, name: &str) -> bool {
    start.name().as_ref().eq_ignore_ascii_case(name)
}

/// An element's attributes, with names lowercased: OPML files vary
/// (`xmlUrl`, `xmlurl`).
fn attributes(start: &BytesStart) -> Attributes {
    let pairs = start
        .attributes()
        .with_checks(false)
        .flatten()
        .map(|attr| {
            let key = attr.key.as_ref().to_ascii_lowercase();
            let value = attr
                .normalized_value_with(XmlVersion::Implicit1_0, 1, resolve_xml_entity)
                .map(|value| value.into_owned())
                .unwrap_or_else(|_| attr.value.to_string());
            (key, value)
        })
        .collect();
    Attributes(pairs)
}

struct Attributes(Vec<(String, String)>);

impl Attributes {
    fn get(&self, name: &str) -> Option<&str> {
        self.0
            .iter()
            .find(|(key, _)| key == name)
            .map(|(_, value)| value.as_str())
    }
}

/// The name a subscription is listed under: its title, or else its URL.
fn name(subscription: &Subscription) -> &str {
    subscription
        .title
        .as_deref()
        .unwrap_or(&subscription.feed_url)
}

fn sort_key(name: &str) -> String {
    name.to_lowercase()
}

fn write_feed(opml: &mut String, subscription: &Subscription, indent: &str) {
    let title = escape(name(subscription));
    let feed_url = escape(&subscription.feed_url);
    let site_url = escape(
        subscription
            .site_url
            .as_deref()
            .unwrap_or(&subscription.feed_url),
    );
    opml.push_str(&format!(
        "{indent}<outline text=\"{title}\" title=\"{title}\" description=\"\" type=\"rss\" \
         version=\"RSS\" htmlUrl=\"{site_url}\" xmlUrl=\"{feed_url}\"/>\n"
    ));
}

/// Escapes text for an attribute value.
fn escape(text: &str) -> String {
    let mut escaped = String::with_capacity(text.len());
    for c in text.chars() {
        match c {
            '&' => escaped.push_str("&amp;"),
            '<' => escaped.push_str("&lt;"),
            '>' => escaped.push_str("&gt;"),
            '"' => escaped.push_str("&quot;"),
            '\n' => escaped.push_str("&#10;"),
            c => escaped.push(c),
        }
    }
    escaped
}
